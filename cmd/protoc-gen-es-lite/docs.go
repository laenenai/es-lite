package main

import (
	"fmt"
	"sort"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
)

// catalogueEntry is one descriptor in the generated projection/reaction
// catalogue (contracts design §9.7/§9.10, convention 30: the catalogue is
// rendered from the descriptors, never hand-maintained).
type catalogueEntry struct {
	kind, name, owner, fetch, rebuild, message, comment string
	consumes, issues                                    []string
}

// kindSection maps a descriptor kind to its section title and order.
var kindSection = map[string]struct {
	title string
	order int
}{
	"REACTION":                   {"Reactions", 0},
	"PROJECTION_KIND_READ_MODEL": {"Read models", 1},
	"PROJECTION_KIND_INDEX":      {"Indexes", 2},
}

// writeCatalogue renders the entries as a markdown file at path (relative to
// the plugin's output directory): one section per owner context, one
// subsection per kind, one heading per descriptor with its leading comment,
// consumed and issued types grouped by package with short names, and
// fetch/rebuild in words.
func writeCatalogue(gen *protogen.Plugin, path string, entries []catalogueEntry) {
	sort.Slice(entries, func(i, j int) bool {
		a, b := entries[i], entries[j]
		if a.owner != b.owner {
			return a.owner < b.owner
		}
		if kindSection[a.kind].order != kindSection[b.kind].order {
			return kindSection[a.kind].order < kindSection[b.kind].order
		}
		return a.name < b.name
	})
	counts := map[string]int{}
	owners := map[string]bool{}
	for _, e := range entries {
		counts[e.kind]++
		owners[e.owner] = true
	}
	g := gen.NewGeneratedFile(path, "")
	g.P("<!-- Code generated by protoc-gen-es-lite (docs=", path, "). DO NOT EDIT. -->")
	g.P()
	g.P("# Projections and reactions")
	g.P()
	g.P(fmt.Sprintf("Rendered from every `(es.v1.projection)` and `(es.v1.reaction)` descriptor: %d reactions, %d read models, %d indexes across %d owner contexts.",
		counts["REACTION"], counts["PROJECTION_KIND_READ_MODEL"], counts["PROJECTION_KIND_INDEX"], len(owners)))
	owner, kind := "\x00", "" // sentinel: the first entry always opens a section, even for an empty owner
	for _, e := range entries {
		if e.owner != owner {
			owner, kind = e.owner, ""
			g.P()
			g.P("## ", owner)
		}
		if e.kind != kind {
			kind = e.kind
			g.P()
			g.P("### ", kindSection[kind].title)
		}
		g.P()
		g.P("#### `", e.name, "` (`", e.message, "`)")
		if e.comment != "" {
			g.P()
			g.P(e.comment)
		}
		g.P()
		g.P("- consumes: ", groupedTypes(e.consumes))
		if e.kind == "REACTION" {
			g.P("- issues: ", groupedTypes(e.issues))
		}
		g.P("- fetch: ", humanise(e.fetch))
		if e.kind != "REACTION" {
			g.P("- rebuild: ", humanise(e.rebuild))
		}
	}
}

// groupedTypes renders fully-qualified type names as "pkg → `A`, `B`; pkg2 →
// `C`", where pkg drops the leading domain./api. and the version segment.
func groupedTypes(types []string) string {
	if len(types) == 0 {
		return "—"
	}
	var order []string
	byPkg := map[string][]string{}
	for _, t := range types {
		pkg, name := shortPackage(t)
		if _, seen := byPkg[pkg]; !seen {
			order = append(order, pkg)
		}
		byPkg[pkg] = append(byPkg[pkg], "`"+name+"`")
	}
	parts := make([]string, len(order))
	for i, pkg := range order {
		parts[i] = pkg + " → " + strings.Join(byPkg[pkg], ", ")
	}
	return strings.Join(parts, "; ")
}

// shortPackage splits "domain.casework.case.v1alpha1.CaseClosed" into
// ("casework.case", "CaseClosed").
func shortPackage(fullName string) (string, string) {
	parts := strings.Split(fullName, ".")
	name := parts[len(parts)-1]
	pkg := parts[:len(parts)-1]
	if len(pkg) > 0 && (pkg[0] == "domain" || pkg[0] == "api") {
		pkg = pkg[1:]
	}
	if n := len(pkg); n > 0 && isVersion(pkg[n-1]) {
		pkg = pkg[:n-1]
	}
	return strings.Join(pkg, "."), name
}

func isVersion(s string) bool {
	if len(s) < 2 || s[0] != 'v' || s[1] < '0' || s[1] > '9' {
		return false
	}
	return true
}

// humanise turns an option enum value into words.
func humanise(v string) string {
	switch v {
	case "FETCH_MODE_STATE_AS_OF_EVENT_VERSION":
		return "state as of the event's version"
	case "FETCH_MODE_METADATA_ONLY":
		return "metadata and payload only (no state)"
	case "REBUILD_MODE_FROM_LOG":
		return "from the log"
	case "", "FETCH_MODE_UNSPECIFIED", "REBUILD_MODE_UNSPECIFIED":
		return "—"
	}
	for _, prefix := range []string{"FETCH_MODE_", "REBUILD_MODE_", "PROJECTION_KIND_"} {
		v = strings.TrimPrefix(v, prefix)
	}
	return strings.ToLower(strings.ReplaceAll(v, "_", " "))
}

// firstParagraph is a message's leading comment up to its first blank line,
// without the comment markers.
func firstParagraph(c protogen.Comments) string {
	var lines []string
	for _, l := range strings.Split(strings.TrimSpace(c.String()), "\n") {
		l = strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(l), "//"))
		if l == "" {
			break
		}
		lines = append(lines, l)
	}
	return strings.Join(lines, " ")
}
