package main

import (
	"fmt"
	"sort"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
)

// catalogueEntry is one row of the generated projection/reaction catalogue
// (contracts design §9.7/§9.10, convention 30: the table is rendered from
// the descriptors, never hand-maintained).
type catalogueEntry struct {
	kind, name, owner, fetch, rebuild, message string
	consumes, issues                           []string
}

// writeCatalogue renders the entries as a markdown file at path (relative to
// the plugin's output directory), grouped by owner context.
func writeCatalogue(gen *protogen.Plugin, path string, entries []catalogueEntry) {
	sort.Slice(entries, func(i, j int) bool {
		if entries[i].owner != entries[j].owner {
			return entries[i].owner < entries[j].owner
		}
		return entries[i].name < entries[j].name
	})
	g := gen.NewGeneratedFile(path, "")
	g.P("<!-- Code generated by protoc-gen-es-lite (docs=", path, "). DO NOT EDIT. -->")
	g.P()
	g.P("# Projections and reactions")
	g.P()
	g.P("| Owner | Name | Kind | Consumes | Issues | Fetch | Rebuild | Declared on |")
	g.P("|---|---|---|---|---|---|---|---|")
	for _, e := range entries {
		g.P(fmt.Sprintf("| %s | `%s` | %s | %s | %s | %s | %s | `%s` |",
			e.owner, e.name, e.kind, codeList(e.consumes), codeList(e.issues), e.fetch, e.rebuild, e.message))
	}
}

func codeList(items []string) string {
	if len(items) == 0 {
		return "—"
	}
	out := make([]string, len(items))
	for i, s := range items {
		out[i] = "`" + s + "`"
	}
	return strings.Join(out, ", ")
}
